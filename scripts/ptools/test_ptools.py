class PublicationBarrierAndIdempotencyTests(unittest.TestCase):
    """Publication is exactly-once, and only after the recorded completed-step barrier."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        self.root = str(make_project(self.tmp))
        self.a = Path(self.root) / "src" / "a.py"
        self.a.write_text("one\ntwo\n")
        self.run = make_cm_run(self.tmp, self.root)

    def begin(self, step, *extra):
        rc, out, err = cm_cli("validate", "--run-dir", self.run, "--dir", self.root,
                              "--task", "t1", "--step", step, "--mode", "begin", *extra)
        self.assertEqual(rc, 0, err)
        info = json.loads(out)
        self.attempt = info["attempt"]
        return info

    def stage(self, step, member="A", generation=1):
        write_launch(self.run, self.attempt, member, generation)
        post = Path(self.tmp) / "post-{}-{}.json".format(step, member)
        post.write_text(json.dumps({"vote": "propose", "proposal": "x", "questions": [],
                                    "code_reads": [{"path": "src/a.py", "lines": [1, 1],
                                                    "observed_sha256": cm.sha256_hex(self.a.read_bytes()),
                                                    "symbol": "foo", "conclusion": "c"}]}))
        rc, out, err = cm_cli("ingest", "--run-dir", self.run, "--dir", self.root, "--task", "t1",
                              "--step", step, "--mode", "stage", "--member", member,
                              "--generation", str(generation), "--post-json", post)
        self.assertEqual(rc, 0, err)

    def publish(self, step):
        rc, out, err = cm_cli("ingest", "--run-dir", self.run, "--dir", self.root,
                              "--task", "t1", "--step", step, "--mode", "publish")
        self.assertEqual(rc, 0, err)
        return json.loads(out)

    def index(self):
        return json.loads((self.run / "codemap" / "index.json").read_bytes())

    def test_publishing_a_partial_step_is_refused_and_loses_nothing(self):
        self.begin("r2")
        self.stage("r2")
        result = self.publish("r2")
        self.assertEqual(result["status"], "not_publishable")
        self.assertFalse(result["step_complete"])
        self.assertEqual(len(self.index()["entries"]), 0, "nothing was published")
        self.assertTrue(staged_payload(self.run, self.attempt, "A"),
                        "the staged work is retained, not silently dropped")
        # once the step completes and the guard passes, the very same staged work publishes
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "end")
        self.assertEqual(self.publish("r2")["status"], "published")
        self.assertEqual(len(self.index()["entries"]), 1)

    def test_pending_verification_never_publishes(self):
        self.begin("r2")
        self.stage("r2")
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "end")
        meta_path = self.run / "codemap" / "attempts" / self.attempt / "meta.json"
        meta = json.loads(meta_path.read_bytes())
        meta["status"] = "pending_verification"
        meta_path.write_bytes(cm.canonical_json(meta))
        self.assertEqual(self.publish("r2")["status"], "not_publishable")
        self.assertEqual(len(self.index()["entries"]), 0)

    def test_republishing_the_same_accepted_event_never_duplicates_reports(self):
        self.begin("r2")
        self.stage("r2")
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "end")
        self.publish("r2")
        first = self.index()
        self.assertEqual(sum(len(e["reports"]) for e in first["entries"].values()), 1)
        # force a genuine re-merge (not merely the already_published short circuit)
        meta_path = self.run / "codemap" / "attempts" / self.attempt / "meta.json"
        meta = json.loads(meta_path.read_bytes())
        meta["status"] = "guard_ok"
        meta_path.write_bytes(cm.canonical_json(meta))
        self.assertEqual(self.publish("r2")["status"], "published")
        again = self.index()
        self.assertEqual(sum(len(e["reports"]) for e in again["entries"].values()), 1,
                         "the same (accepted event, position) is ingested exactly once")
        self.assertEqual(len(again["unbound"]), len(first["unbound"]))
        self.assertEqual(len(again["diagnostics"]), len(first["diagnostics"]))

    def test_a_new_accepted_event_is_a_distinct_report_even_with_identical_content(self):
        self.begin("r2")
        self.stage("r2", member="A")
        self.stage("r2", member="B")
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "end")
        self.publish("r2")
        reports = [r for e in self.index()["entries"].values() for r in e["reports"]]
        self.assertEqual(len(reports), 2)
        self.assertEqual(sorted(r["reader"]["member"] for r in reports), ["A", "B"])

    def test_an_entry_never_borrows_a_validation_that_did_not_cover_it(self):
        """The end-of-step guard covers the sources the frozen view exposed. A source first
        captured DURING the step was not in that guard, so it must not be stamped with that
        validation's id as if it had been verified by it."""
        self.begin("r2")
        self.stage("r2")
        rc, out, _ = cm_cli("validate", "--run-dir", self.run, "--dir", self.root,
                            "--task", "t1", "--step", "r2", "--mode", "end")
        snap = json.loads(out)["validation_snapshot"]
        self.publish("r2")
        entry = list(self.index()["entries"].values())[0]
        self.assertIsNone(entry["freshness"]["snapshot_id"])
