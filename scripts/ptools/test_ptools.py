EM = "—"  # the em dash council.sh puts in every task header
TAIL_RULE = "Nothing may follow the JSON tail.\n"


def prompt_round_n(task, rnd, candidate_id, candidate, relayed, answers_block="", rules=False):
    """Reproduce the shape council.sh prompt_roundN() emits, for section accounting."""
    out = ""
    if rules:
        out += "You are member A of a council of 3 AI agents.\n...rules...\n" + TAIL_RULE + "\n"
    out += "=== TASK {} {} round {} of 4 ===\n".format(task, EM, rnd)
    out += "Candidate for this round {} proposed by member A. Vote on this EXACT text:\n".format(EM)
    out += "<<<CANDIDATE {}\n{}\n>>>\n\n".format(candidate_id, candidate)
    out += "Posts of the other members in round {}:\n".format(rnd - 1)
    for member, body in relayed:
        out += "--- member {} ---\n{}\n\n".format(member, body)
    if not relayed:
        out += "\n"
    out += answers_block
    out += "Your job this round: reply to the other members.\n"
    return out.encode()


def filler(tag, n):
    """Padding with no internal repeat >= MIN_BYTES, so fixtures test only what they plant."""
    out = []
    while sum(len(x) for x in out) < n:
        out.append("{}-{:06d}-".format(tag, len(out)))
    return "".join(out)[:n]


def post(proposal, prose="Prose."):
    tail = json.dumps({"vote": "propose", "proposal": proposal, "questions": []})
    return "{}\n```json\n{}\n```".format(prose, tail), tail


def make_run(tmp, prompts, state):
    run = Path(tmp)
    (run / "prompts").mkdir(parents=True, exist_ok=True)
    (run / "posts").mkdir(parents=True, exist_ok=True)
    for name, data in prompts.items():
        (run / "prompts" / name).write_bytes(data)
    (run / "state.json").write_text(json.dumps(state))
    return run


def run_cli(script, *args):
    proc = subprocess.run([sys.executable, str(HERE / script)] + [str(a) for a in args],
                          capture_output=True, text=True)
    return proc.returncode, proc.stdout, proc.stderr


def planted(blocks, block, times):
    """The tool reports MAXIMAL repeats, so a planted block may be reported with
    the identical bytes that happen to surround every occurrence. Assert containment."""
    hits = [(b, offs) for b, offs in blocks if block.encode() in b and len(offs) == times]
    return hits


def tree_fingerprint(root):
    out = {}
    for path in sorted(Path(root).rglob("*")):
        if path.is_file():
            out[str(path.relative_to(root))] = path.read_bytes()
    return out


class DedupBlocks(unittest.TestCase):
    """dedup_check.repeated_blocks: the byte-level duplicate finder."""

    def test_empty_input_is_handled(self):
        self.assertEqual(dedup_check.repeated_blocks(b""), [])

    def test_unique_text_has_no_repeats(self):
        data = ("".join("line %04d unique content here\n" % i for i in range(200))).encode()
        self.assertEqual(dedup_check.repeated_blocks(data), [])

    def test_repeat_at_threshold_is_found_with_offsets(self):
        block = ("R" * 100 + "-tail-of-the-repeated-block-0123456789abcdef")[:dedup_check.MIN_BYTES]
        self.assertEqual(len(block), 128)
        data = (filler("A", 300) + block + filler("B", 300) + block + filler("C", 300)).encode()
        blocks = dedup_check.repeated_blocks(data)
        hits = planted(blocks, block, 2)
        self.assertEqual(len(hits), 1, blocks)
        reported, offsets = hits[0]
        self.assertEqual(offsets[1] - offsets[0], len(block) + 300,
                         "the two planted copies are 300 filler bytes apart")
        self.assertIn(block.encode(), reported)

    def test_repeat_below_threshold_is_ignored(self):
        block = filler("z", 127)
        data = (filler("A", 300) + block + filler("B", 300) + block + filler("C", 300)).encode()
        self.assertEqual([b for b in dedup_check.repeated_blocks(data) if b[0] == block.encode()], [])

    def test_three_occurrences_are_all_reported(self):
        block = filler("REPEATED", 150)
        self.assertEqual(len(block), 150)
        data = (filler("x", 200) + block + filler("y", 200) + block + filler("z", 200) + block).encode()
        self.assertEqual(len(planted(dedup_check.repeated_blocks(data), block, 3)), 1)

    def test_sub_block_covered_by_a_larger_repeat_is_not_reported_twice(self):
        block = filler("COVERING", 256)
        data = (filler("a", 300) + block + filler("b", 300) + block).encode()
        blocks = dedup_check.repeated_blocks(data)
        self.assertEqual(len(blocks), 1, blocks)
        self.assertGreaterEqual(len(blocks[0][0]), 256)
        self.assertIn(block.encode(), blocks[0][0])

    def test_overlapping_run_counts_non_overlapping_occurrences_only(self):
        data = b"m" * 300  # every window overlaps every other
        for block, offsets in dedup_check.repeated_blocks(data):
            starts = sorted(offsets)
            for earlier, later in zip(starts, starts[1:]):
                self.assertGreaterEqual(later - earlier, len(block),
                                        "reported occurrences must not overlap")

    def test_multibyte_utf8_is_handled_on_bytes(self):
        block = "café-雪-" * 24  # multi-byte; >=128 bytes
        self.assertGreaterEqual(len(block.encode()), dedup_check.MIN_BYTES)
        data = (filler("A", 200) + block + filler("B", 200) + block).encode()
        hits = planted(dedup_check.repeated_blocks(data), block, 2)
        self.assertEqual(len(hits), 1)
        # the reporting path must not raise on a preview cut inside a code point
        hits[0][0][:100].decode("utf-8", errors="replace")


