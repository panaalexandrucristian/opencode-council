class CaptureSeamTests(unittest.TestCase):
    """Deterministic tests at the real open/read/stat seams."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        self.root = os.path.realpath(str(make_project(self.tmp)))
        self.a = Path(self.root) / "src" / "a.py"
        self.a.write_text("body\n")

    def test_an_absolute_path_is_rejected_on_the_original_spelling_not_normalised_away(self):
        with self.assertRaises(cm.CaptureError) as ctx:
            cm.validated_display_path("/b")
        self.assertEqual(ctx.exception.reason, "absolute_path")
        # and the normaliser alone would have silently turned it into a relative path
        self.assertEqual(cm.normalize_display_path("/b"), "b")

    def test_an_embedded_nul_path_is_a_per_item_reason_not_an_aborting_valueerror(self):
        with self.assertRaises(cm.CaptureError) as ctx:
            cm.validated_display_path("src/a\x00.py")
        self.assertEqual(ctx.exception.reason, "invalid_path")

    def test_an_unreadable_parent_directory_is_unreadable_not_a_confirmed_change(self):
        d = Path(self.root) / "locked"
        d.mkdir()
        (d / "f.py").write_text("x\n")
        os.chmod(d, 0o000)
        self.addCleanup(os.chmod, d, 0o755)
        if os.geteuid() == 0:
            self.skipTest("running as root; directory permissions do not apply")
        cap = cm.bounded_capture(self.root, "locked/f.py")
        self.assertEqual(cap.status, "unstable")
        self.assertEqual(cap.reason, "unreadable")
        self.assertNotIn(cap.reason, cm.CONFIRMED_CHANGE_REASONS,
                         "a chmod on a parent must never invalidate a round's votes")

    def test_a_symlink_that_stays_inside_the_root_is_permitted_and_captured(self):
        """The no-follow walk runs over the ALREADY-RESOLVED real path, so an ordinary in-root
        symlink is legitimate (the ratified design permits it) — what no-follow catches is a
        symlink that appears between resolution and open."""
        (Path(self.root) / "src" / "t.py").write_text("t\n")
        (Path(self.root) / "src" / "s.py").symlink_to("t.py")
        cap = cm.bounded_capture(self.root, "src/s.py")
        self.assertEqual(cap.status, "ok")
        self.assertEqual(cap.data, b"t\n")
        self.assertTrue(cap.resolved_path.endswith("t.py"), "the identity is the real target")

    def test_a_component_swapped_for_a_symlink_after_resolution_is_a_retarget(self):
        (Path(self.root) / "src" / "real.py").write_text("real\n")
        plain = Path(self.root) / "src" / "p.py"
        plain.write_text("plain\n")
        real_resolve = cm.safe_resolve

        def resolve_then_swap(root, rel):
            resolved = real_resolve(root, rel)
            if rel == "src/p.py" and not plain.is_symlink():
                plain.unlink()                       # between resolution and open
                plain.symlink_to("real.py")
            return resolved

        with unittest.mock.patch.object(cm, "safe_resolve", resolve_then_swap):
            with self.assertRaises(cm.CaptureError) as ctx:
                cm._open_norace(self.root, "src/p.py")
        self.assertEqual(ctx.exception.reason, "retargeted")

    def test_a_completed_read_rejected_after_the_fact_still_reports_its_work(self):
        """The file grows at EOF, between the last read() and the after-read fstat: every byte was
        genuinely read and genuinely hashed, and the rejection does not erase that work."""
        real_read = os.read
        grown = {"n": 0}

        def read_then_grow(fd, n):
            chunk = real_read(fd, n)
            if not chunk and grown["n"] < 2:     # EOF reached: the whole file was read
                grown["n"] += 1
                with open(self.a, "ab") as fh:
                    fh.write(b"x")
            return chunk

        with unittest.mock.patch.object(cm.os, "read", read_then_grow):
            cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "unstable")
        self.assertEqual(cap.reason, "mutated_during_read")
        self.assertEqual(cap.attempts, 2, "exactly two bounded attempts, no more")
        # attempt 1 read "body\n" (5), attempt 2 read the grown "body\nx" (6); each was hashed
        self.assertEqual(cap.bytes_read, 11)
        self.assertEqual(cap.bytes_hashed, 11)
        # and a guard over that source reports "we could not check", never "current"
        guard = [{"root": self.root, "path": "src/a.py", "resolved_path": str(self.a),
                  "source_sha256": cm.sha256_hex(self.a.read_bytes())}]
        grown["n"] = 0
        with unittest.mock.patch.object(cm.os, "read", read_then_grow):
            status, results, stats = cm.verify_guard(self.root, guard)
        self.assertEqual(status, "pending_verification", "unstable is never reported as current")
        self.assertEqual(results[0]["status"], "unstable")
        self.assertGreater(stats["bytes_read"], 0, "the guard reports the work it really did")
        self.assertGreater(stats["bytes_hashed"], 0)

    def test_a_partial_read_that_then_fails_counts_read_bytes_and_no_hashing(self):
        """Work that happened is counted; work that did not is not. A read aborted mid-file was
        never hashed, so bytes_hashed stays 0 while bytes_read records what came off the fd."""
        real_read = os.read
        calls = {"n": 0}

        def flaky(fd, n):
            calls["n"] += 1
            if calls["n"] % 2 == 1:
                return real_read(fd, 3)          # a partial chunk...
            raise OSError(5, "simulated I/O error")   # ...then the read fails

        with unittest.mock.patch.object(cm.os, "read", flaky):
            cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "unstable")
        self.assertEqual(cap.reason, "unreadable")
        self.assertEqual(cap.attempts, 2)
        self.assertEqual(cap.bytes_read, 6, "3 bytes actually read on each of the two attempts")
        self.assertEqual(cap.bytes_hashed, 0, "a read that never completed was never hashed")
        self.assertNotIn(cap.reason, cm.CONFIRMED_CHANGE_REASONS)

    def test_a_symlink_that_escapes_the_root_after_the_read_still_reports_its_work(self):
        """The defect: an in-root symlink is retargeted OUTSIDE the root at EOF, after the read
        loop finished. The source is rightly rejected, but the escape is raised inside
        safe_resolve, which knows nothing about this attempt — so the five bytes really read and
        really hashed must still be reported, not silently accounted for as zero work."""
        outside = Path(self.tmp) / "outside.py"
        outside.write_text("gone\n")
        target = Path(self.root) / "src" / "target.py"
        target.write_text("body\n")                      # five bytes
        link = Path(self.root) / "src" / "link.py"
        link.symlink_to("target.py")                     # in-root and valid when it is opened
        real_read, real_hash = os.read, cm.sha256_hex
        actual = {"read": 0, "hashed": 0, "escaped": False}

        def read_then_escape(fd, n):
            chunk = real_read(fd, n)
            actual["read"] += len(chunk)
            if not chunk and not actual["escaped"]:      # EOF: the whole file has been read
                actual["escaped"] = True
                link.unlink()
                link.symlink_to(outside)
            return chunk

        def counting_hash(data):
            actual["hashed"] += len(data)
            return real_hash(data)

        with unittest.mock.patch.object(cm.os, "read", read_then_escape), \
                unittest.mock.patch.object(cm, "sha256_hex", counting_hash):
            cap = cm.bounded_capture(self.root, "src/link.py")
        self.assertEqual(cap.status, "error")
        self.assertEqual(cap.reason, "escape", "an escaped source is still rejected immediately")
        self.assertEqual(actual["read"], 5, "instrumented: five bytes really came off the fd")
        self.assertEqual(actual["hashed"], 5, "instrumented: those five bytes were really hashed")
        self.assertEqual(cap.bytes_read, 5, "the work done is reported, not discarded")
        self.assertEqual(cap.bytes_hashed, 5)
        # and that work reaches the accounting path the run's reporting actually sums
        stats = cm.new_stats()
        cm.account(stats, cap)
        self.assertEqual((stats["bytes_read"], stats["bytes_hashed"]), (5, 5))
        self.assertEqual(stats["capture_failures"], 1)
        # the same escape seen through the freshness guard: a confirmed change, work still counted
        link.unlink()
        link.symlink_to(outside)
        guard = [{"root": self.root, "path": "src/link.py",
                  "resolved_path": str(Path(self.root) / "src" / "target.py"),
                  "source_sha256": cm.sha256_hex(b"body\n")}]
        status, results, gstats = cm.verify_guard(self.root, guard)
        self.assertEqual(status, "changed", "an escaped source is a demonstrated change")
        self.assertEqual(results[0]["reason"], "escape")
        # and the same file captured without the escape is not double-counted
        link.unlink()
        link.symlink_to("target.py")
        ok = cm.bounded_capture(self.root, "src/link.py")
        self.assertEqual(ok.status, "ok")
        self.assertEqual((ok.bytes_read, ok.bytes_hashed), (10, 10),
                         "two complete reads of five bytes, each hashed once")

    def test_a_post_read_filesystem_failure_is_unreadable_and_keeps_its_counters(self):
        """A post-read failure that the inner read handler never saw: the re-resolution itself
        fails with an I/O error. That is "we could not look", never a confirmed change, and the
        bytes already read and hashed are still reported."""
        real_realpath = os.path.realpath
        calls = {"n": 0}

        def flaky_realpath(p):
            # the pre-open resolution succeeds; only the post-read re-resolution fails
            if str(p).endswith("src/a.py"):
                calls["n"] += 1
                if calls["n"] % 2 == 0:
                    raise OSError(5, "simulated I/O error")
            return real_realpath(p)

        with unittest.mock.patch.object(cm.os.path, "realpath", flaky_realpath):
            cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "unstable")
        self.assertEqual(cap.reason, "unreadable")
        self.assertNotIn(cap.reason, cm.CONFIRMED_CHANGE_REASONS,
                         "a failed re-resolution is not a demonstrated change")
        self.assertEqual(cap.attempts, 2)
        self.assertEqual(cap.bytes_read, 10, "five bytes on each of the two attempts")
        self.assertEqual(cap.bytes_hashed, 10, "each completed read was hashed before the failure")

    def test_a_failure_closing_the_descriptor_after_eof_is_unreadable_and_hashes_nothing(self):
        """The defect: the read finished, and then descriptor cleanup itself failed. os.close runs
        in the `finally` that ends the inner read handler, so no inner handler can ever see it —
        the raw OSError left the whole capture operation, past every accounting boundary, and
        bounded_capture propagated it instead of returning a result. It must become the ordinary
        retry-worthy `unreadable`, carrying the bytes genuinely read; nothing was hashed, because
        the hashing happens after the close and never ran."""
        real_read, real_close = os.read, os.close
        at_eof = set()
        seen = {"read": 0, "closes": 0}

        def read_to_eof(fd, n):
            chunk = real_read(fd, n)
            seen["read"] += len(chunk)
            if not chunk:
                at_eof.add(fd)          # this descriptor is the regular file, read to the end
            return chunk

        def close_then_fail(fd):
            real_close(fd)              # really closed: the failure injects no descriptor leak
            if fd in at_eof:
                at_eof.discard(fd)
                seen["closes"] += 1
                raise OSError(5, "simulated I/O error closing the file")

        with unittest.mock.patch.object(cm.os, "read", read_to_eof), \
                unittest.mock.patch.object(cm.os, "close", close_then_fail):
            cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "unstable", "a result, not a raw OSError out of the operation")
        self.assertEqual(cap.reason, "unreadable")
        self.assertNotIn(cap.reason, cm.CONFIRMED_CHANGE_REASONS,
                         "a failed close is not a demonstrated change")
        self.assertEqual(cap.attempts, 2)
        self.assertEqual(seen["closes"], 2, "the failure really fired on both attempts")
        self.assertEqual(cap.bytes_read, 10, "five bytes on each of the two attempts")
        self.assertEqual(cap.bytes_hashed, 0,
                         "the close failed before the hash: hashing that never happened is never counted")
        self.assertEqual(seen["read"], 10, "instrumented: exactly those bytes came off the fd")
        # and those totals reach the accounting path the run's reporting actually sums
        stats = cm.new_stats()
        cm.account(stats, cap)
        self.assertEqual((stats["bytes_read"], stats["bytes_hashed"]), (10, 0))
        self.assertEqual(stats["capture_unstable"], 1, "retry-worthy, not a confirmed failure")
        self.assertEqual(stats["read_attempts"], 2)

