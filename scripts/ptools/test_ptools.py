class SectionAccounting(unittest.TestCase):
    """prompt_report.section_bytes: every byte must land in exactly one section."""

    def setUp(self):
        self.state = {"config": {"tasks": [{"id": "t1", "text": "Do the thing.", "execute": False}]},
                      "answers": []}

    def partition_holds(self, data, state=None):
        counts = prompt_report.section_bytes(data, state or self.state)
        self.assertEqual(sum(counts.values()), len(data),
                         "sections must partition every byte")
        return counts

    def test_partition_holds_for_a_round_prompt(self):
        body, _ = post("Some proposal text.")
        data = prompt_round_n("t1", 2, "t1-c1", "CANDIDATE BODY", [("B", body)])
        counts = self.partition_holds(data)
        self.assertGreater(counts["candidate"], 0)
        self.assertGreater(counts["relayed posts"], 0)

    def test_partition_holds_with_rules_and_notes(self):
        data = ("You are member A of a council of 3 AI agents.\n" + TAIL_RULE +
                "\nHandover note from your predecessor session (same member id):\n"
                "<<<HANDOVER\nnote body\n>>>\n\n"
                "=== TASK t1 {} round 2 of 4 ===\nbody\n\nYour job this round: x\n".format(EM)).encode()
        counts = self.partition_holds(data)
        self.assertGreater(counts["rules"], 0)
        self.assertGreater(counts["replacement notes"], 0)

    def test_candidate_bytes_match_the_candidate_block(self):
        candidate = "CANDIDATE BODY\nsecond line"
        body, _ = post("unrelated")
        data = prompt_round_n("t1", 2, "t1-c1", candidate, [("B", body)])
        counts = prompt_report.section_bytes(data, self.state)
        block = "<<<CANDIDATE t1-c1\n{}\n>>>\n".format(candidate).encode()
        self.assertEqual(counts["candidate"], len(block))

    def test_answers_block_is_attributed_to_answers(self):
        state = dict(self.state, answers=[{"task": "t1", "member": "A",
                                           "question": "Q?", "answer": "A!"}])
        block = (prompt_report.ANSWERS.decode() + "- Q (member A): Q?\n  A: A!\n")
        body, _ = post("unrelated")
        data = prompt_round_n("t1", 2, "t1-c1", "CAND", [("B", body)], answers_block=block)
        counts = self.partition_holds(data, state)
        self.assertEqual(counts["answers"], len(block.encode()))

    def test_quoted_answers_heading_inside_a_post_is_not_an_answers_section(self):
        state = dict(self.state, answers=[{"task": "t1", "member": "A",
                                           "question": "Q?", "answer": "A!"}])
        body, _ = post("I quote: " + prompt_report.ANSWERS.decode() + "- Q (member A): Q?\n  A: A!\n")
        data = prompt_round_n("t1", 2, "t1-c1", "CAND", [("B", body)])
        counts = self.partition_holds(data, state)
        self.assertEqual(counts["answers"], 0, "a member's quotation is member text, not an answers section")

    def test_task_text_counted_only_in_round_one(self):
        text = self.state["config"]["tasks"][0]["text"]
        first = "=== TASK t1 {} round 1 of 4 ===\n{}\n\nYour job this round: x\n".format(EM, text).encode()
        later = "=== TASK t1 {} round 2 of 4 ===\n{}\n\nYour job this round: x\n".format(EM, text).encode()
        self.assertEqual(self.partition_holds(first)["task text"], len(text.encode()))
        self.assertEqual(self.partition_holds(later)["task text"], 0)

    def test_prompt_without_a_task_header_is_all_instructions(self):
        data = b"Your previous reply could not be used: re-send it.\n"
        counts = self.partition_holds(data)
        self.assertEqual(counts["instructions"], len(data))


class MeasureOneReplay(unittest.TestCase):
    """prompt_report.measure_one: the de-duplication saving replay."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        self.candidate = "CANDIDATE BODY that is long enough to be worth de-duplicating. " * 6
        self.state = {"config": {"tasks": [{"id": "t1", "text": "Do it.", "execute": False}]},
                      "answers": [], "members": [{"id": "A"}, {"id": "B"}],
                      "candidate": {"id": "t1-c1", "member": "A", "text": self.candidate}}

    def build(self, relayed_proposal):
        body, _ = post(relayed_proposal)
        (Path(self.tmp) / "posts").mkdir(parents=True, exist_ok=True)
        (Path(self.tmp) / "posts" / "t1-r1-B.md").write_text(body)
        (Path(self.tmp) / "posts" / "t1-r1-B.json").write_text(
            json.dumps({"vote": "propose", "proposal": relayed_proposal, "questions": []}))
        data = prompt_round_n("t1", 2, "t1-c1", self.candidate, [("B", body)])
        run = make_run(self.tmp, {"t1-r2-A.md": data}, self.state)
        return data, run

    def test_identical_proposal_produces_a_saving_and_keeps_the_text_once(self):
        data, run = self.build(self.candidate)
        after, events = prompt_report.measure_one(data, "t1-r2-A.md", run, self.state)
        self.assertTrue(events, "an exact candidate copy in a relayed post must be de-duplicated")
        saving = sum(e[1] for e in events)
        self.assertGreater(saving, 0)
        self.assertEqual(len(after), len(data) - saving, "reported saving must match the replayed bytes")
        self.assertEqual(after.count(self.candidate.encode()), 1,
                         "the candidate text must survive exactly once")

    def test_different_proposal_is_left_untouched(self):
        data, run = self.build("A completely different proposal. " * 6)
        after, events = prompt_report.measure_one(data, "t1-r2-A.md", run, self.state)
        self.assertEqual(events, [])
        self.assertEqual(after, data)

    def test_one_character_difference_is_not_de_duplicated(self):
        data, run = self.build(self.candidate[:-1] + "!")
        after, events = prompt_report.measure_one(data, "t1-r2-A.md", run, self.state)
        self.assertEqual(events, [], "comparison must be byte-exact")
        self.assertEqual(after, data)


