class HistoricalBindingIdentityTests(unittest.TestCase):
    """A digest proves only that SOME file held those bytes. Binding a claim to a path requires a
    recorded version of THAT path holding them."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        self.root = str(make_project(self.tmp))
        self.a = Path(self.root) / "src" / "a.py"
        self.b = Path(self.root) / "src" / "b.py"
        self.run = make_cm_run(self.tmp, self.root)

    def begin(self, step):
        rc, out, err = cm_cli("validate", "--run-dir", self.run, "--dir", self.root,
                              "--task", "t1", "--step", step, "--mode", "begin")
        self.assertEqual(rc, 0, err)
        self.attempt = json.loads(out)["attempt"]
        write_launch(self.run, self.attempt, "A")
        return self.attempt

    def stage(self, step, path, digest, member="A"):
        write_launch(self.run, self.attempt, member)
        post = Path(self.tmp) / "post-{}-{}.json".format(step, member)
        post.write_text(json.dumps({"vote": "agree", "questions": [],
                                    "code_reads": [{"path": path, "observed_sha256": digest}]}))
        rc, out, err = cm_cli("ingest", "--run-dir", self.run, "--dir", self.root, "--task", "t1",
                              "--step", step, "--mode", "stage", "--member", member,
                              "--generation", "1", "--post-json", post)
        self.assertEqual(rc, 0, err)
        return staged_payload(self.run, self.attempt, member)

    def test_a_digest_captured_from_another_file_never_authenticates_this_path(self):
        self.b.write_text("B CONTENT\n")
        b_digest = cm.sha256_hex(self.b.read_bytes())
        self.begin("r2")
        self.stage("r2", "src/b.py", b_digest)          # records the version for src/b.py
        # now a claim about src/a.py quoting src/b.py's digest: the object exists, the identity
        # does not, so the claim must stay unbound
        self.a.write_text("A CONTENT\n")
        self.begin("r3")
        staged = self.stage("r3", "src/a.py", b_digest)
        self.assertEqual([u["reason"] for u in staged["unbound"]], ["digest_mismatch"])
        self.assertEqual([r for e in staged["entries"].values() for r in e["reports"]], [],
                         "equal bytes somewhere else are not evidence about this path")
        entry = list(staged["entries"].values())[0]
        self.assertEqual(entry["shell"]["source_sha256"], cm.sha256_hex(self.a.read_bytes()),
                         "the entry describes today's src/a.py, never src/b.py's version")

    def test_a_historical_version_of_this_path_does_bind_and_keeps_its_own_resolved_path(self):
        real = Path(self.root) / "src" / "real1.py"
        real.write_text("V1\n")
        link = Path(self.root) / "src" / "a.py"
        link.symlink_to("real1.py")
        v1 = cm.sha256_hex(b"V1\n")
        self.begin("r2")
        self.stage("r2", "src/a.py", v1)
        # retarget to a DIFFERENT file with the same content: today's resolved_path changed
        real2 = Path(self.root) / "src" / "real2.py"
        real2.write_text("V2\n")
        link.unlink()
        link.symlink_to("real2.py")
        self.begin("r3")
        staged = self.stage("r3", "src/a.py", v1)
        entry = list(staged["entries"].values())[0]
        self.assertTrue(entry["historical"])
        self.assertEqual(entry["shell"]["source_sha256"], v1)
        self.assertTrue(entry["shell"]["resolved_path"].endswith("real1.py"),
                        "a historical version keeps the path as it resolved THEN, not today's target")
        self.assertEqual([r["observed_sha256"] for e in staged["entries"].values()
                          for r in e["reports"]], [v1])

    def test_historical_evidence_survives_the_live_file_being_deleted(self):
        self.a.write_text("ONLY VERSION\n")
        v = cm.sha256_hex(self.a.read_bytes())
        self.begin("r2")
        self.stage("r2", "src/a.py", v)
        self.a.unlink()                                  # the live file is gone
        self.begin("r3")
        staged = self.stage("r3", "src/a.py", v)
        self.assertEqual(staged["unbound"], [], "recorded history does not depend on the live file")
        entry = list(staged["entries"].values())[0]
        self.assertTrue(entry["historical"])
        self.assertEqual(entry["shell"]["source_sha256"], v)

    def test_a_historical_binding_is_never_published_as_current(self):
        self.a.write_text("V1\n")
        v1 = cm.sha256_hex(self.a.read_bytes())
        self.begin("r2")
        self.stage("r2", "src/a.py", v1)
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "end")
        cm_cli("ingest", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r2", "--mode", "publish")
        self.a.write_text("V2 IS LONGER\n")
        self.begin("r3")
        self.stage("r3", "src/a.py", v1)
        cm_cli("validate", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r3", "--mode", "end")
        cm_cli("ingest", "--run-dir", self.run, "--dir", self.root, "--task", "t1", "--step", "r3", "--mode", "publish")
        index = json.loads((self.run / "codemap" / "index.json").read_bytes())
        hist = [e for e in index["entries"].values() if e["source_sha256"] == v1]
        self.assertTrue(hist)
        for e in hist:
            self.assertFalse(e["freshness"]["current_at_snapshot"],
                             "a version the path no longer holds is never labelled current")
            self.assertNotEqual(e["freshness"]["status"], "current")


