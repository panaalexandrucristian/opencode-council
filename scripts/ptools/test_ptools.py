class BoundedCaptureTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        self.root = os.path.realpath(str(make_project(self.tmp)))
        self.path = Path(self.root) / "src" / "a.py"
        self.path.write_text("stable content\n")

    def test_each_of_the_two_complete_reads_is_read_and_hashed_in_its_own_right(self):
        cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "ok")
        self.assertEqual(cap.data, b"stable content\n")
        # the ratified capture contract is TWO complete reads, each with its own full-file hash,
        # so the stability comparison is digest-vs-digest and the accounting is the work done
        self.assertEqual(cap.bytes_read, len(cap.data) * 2, "two complete reads are two reads")
        self.assertEqual(cap.bytes_hashed, len(cap.data) * 2, "and two full hashes are two hashes")
        self.assertEqual(cap.attempts, 1)

    def test_a_failed_attempt_still_counts_the_work_it_really_did(self):
        real = cm.capture_once
        calls = {"n": 0}

        def flaky(root, rel):
            calls["n"] += 1
            if calls["n"] == 2:                      # the second read of the first attempt fails
                raise cm.CaptureError("unreadable", "transient")
            return real(root, rel)

        with unittest.mock.patch.object(cm, "capture_once", flaky):
            cap = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(cap.status, "ok")
        self.assertEqual(cap.attempts, 2)
        n = len(b"stable content\n")
        self.assertEqual(cap.bytes_read, n * 3, "the discarded first read really was read")
        self.assertEqual(cap.bytes_hashed, n * 3, "and really was hashed")

    def test_a_file_mutated_during_a_single_read_is_never_accepted(self):
        """The after-read fstat is the point of this: the bytes were read cleanly, but the file
        they came from no longer matches what it was when the read started."""
        a = self.path
        real_read = os.read
        state = {"mutated": False}

        def mutating_read(fd, n):
            chunk = real_read(fd, n)
            if chunk and not state["mutated"]:
                state["mutated"] = True
                a.write_text("stable content CHANGED\n")   # while the read is in flight
            return chunk

        with unittest.mock.patch("os.read", mutating_read):
            with self.assertRaises(cm.CaptureError) as ctx:
                cm.capture_once(self.root, "src/a.py")
        self.assertEqual(ctx.exception.reason, "mutated_during_read")

    def test_mutation_between_reads_is_unstable_not_silently_current(self):
        real = cm.capture_once
        calls = {"n": 0}

        def flaky(root, rel):
            calls["n"] += 1
            r = real(root, rel)
            if calls["n"] % 2 == 1:
                return r
            return cm.OneRead(r.data + b"MUTATED", cm.sha256_hex(r.data + b"MUTATED"),
                              r.st_before, r.st_after, r.resolved)

        with unittest.mock.patch.object(cm, "capture_once", flaky):
            result = cm.bounded_capture(self.root, "src/a.py")
        self.assertEqual(result.status, "unstable")

    def test_at_most_two_capture_attempts(self):
        real = cm.capture_once
        calls = {"n": 0}

        def counting(root, rel):
            calls["n"] += 1
            return real(root, rel)

        with unittest.mock.patch.object(cm, "capture_once", counting):
            cm.bounded_capture(self.root, "src/a.py")
        self.assertLessEqual(calls["n"], 4, "at most two attempts x two reads each")


